# Generate the 5-band biquad coefficient ROM for audio_eq.v.
# 5 bands x 9 gain steps (-12..+12 dB in 3 dB steps) x 5 coefficients = 225 words.
# Coefficients are normalized by a0 and quantized to signed Q3.13.
import math

FS = 48000.0
BANDS = [
    ("LOW_SHELF", 100.0, 0.0, 1.0),
    ("PEAK", 300.0, 0.9, 0.0),
    ("PEAK", 1000.0, 0.9, 0.0),
    ("PEAK", 3000.0, 0.9, 0.0),
    ("HIGH_SHELF", 8000.0, 0.0, 1.0),
]


def clamp16(v):
    return max(-32768, min(32767, int(round(v))))


def q313(v):
    return clamp16(round(v * 8192.0))


def low_shelf(f0, gain_db, slope):
    A = 10.0 ** (gain_db / 40.0)
    w0 = 2.0 * math.pi * f0 / FS
    cw = math.cos(w0)
    sw = math.sin(w0)
    alpha = sw / 2.0 * math.sqrt((A + 1.0 / A) * (1.0 / slope - 1.0) + 2.0)
    b0 = A * ((A + 1) - (A - 1) * cw + 2 * math.sqrt(A) * alpha)
    b1 = 2 * A * ((A - 1) - (A + 1) * cw)
    b2 = A * ((A + 1) - (A - 1) * cw - 2 * math.sqrt(A) * alpha)
    a0 = (A + 1) + (A - 1) * cw + 2 * math.sqrt(A) * alpha
    a1 = -2 * ((A - 1) + (A + 1) * cw)
    a2 = (A + 1) + (A - 1) * cw - 2 * math.sqrt(A) * alpha
    return b0, b1, b2, a1, a2, a0


def high_shelf(f0, gain_db, slope):
    A = 10.0 ** (gain_db / 40.0)
    w0 = 2.0 * math.pi * f0 / FS
    cw = math.cos(w0)
    sw = math.sin(w0)
    alpha = sw / 2.0 * math.sqrt((A + 1.0 / A) * (1.0 / slope - 1.0) + 2.0)
    b0 = A * ((A + 1) + (A - 1) * cw + 2 * math.sqrt(A) * alpha)
    b1 = -2 * A * ((A - 1) + (A + 1) * cw)
    b2 = A * ((A + 1) + (A - 1) * cw - 2 * math.sqrt(A) * alpha)
    a0 = (A + 1) - (A - 1) * cw + 2 * math.sqrt(A) * alpha
    a1 = 2 * ((A - 1) - (A + 1) * cw)
    a2 = (A + 1) - (A - 1) * cw - 2 * math.sqrt(A) * alpha
    return b0, b1, b2, a1, a2, a0


def peaking(f0, gain_db, q):
    A = 10.0 ** (gain_db / 40.0)
    w0 = 2.0 * math.pi * f0 / FS
    cw = math.cos(w0)
    sw = math.sin(w0)
    alpha = sw / (2.0 * q)
    b0 = 1 + alpha * A
    b1 = -2 * cw
    b2 = 1 - alpha * A
    a0 = 1 + alpha / A
    a1 = -2 * cw
    a2 = 1 - alpha / A
    return b0, b1, b2, a1, a2, a0


def coeffs(band, gain_db):
    kind, f0, q, slope = BANDS[band]
    if abs(gain_db) < 1e-9:
        return [8192, 0, 0, 0, 0]
    if kind == "PEAK":
        b0, b1, b2, a1, a2, a0 = peaking(f0, gain_db, q)
    elif kind == "LOW_SHELF":
        b0, b1, b2, a1, a2, a0 = low_shelf(f0, gain_db, slope)
    else:
        b0, b1, b2, a1, a2, a0 = high_shelf(f0, gain_db, slope)
    return [q313(b0 / a0), q313(b1 / a0), q313(b2 / a0),
            q313(a1 / a0), q313(a2 / a0)]


rows = []
for b in range(5):
    for g in range(9):
        c = coeffs(b, (g - 4) * 3.0)
        rows.append(c)

assert len(rows) == 45
lines = []
lines.append("`timescale 1ns/1ps")
lines.append("")
lines.append("// Generated by scripts/gen_audio_eq_coeffs.py. Do not edit by hand.")
lines.append("module audio_eq_coeff_rom (")
lines.append("    input  wire        clk,")
lines.append("    input  wire [7:0]  addr,")
lines.append("    output reg  signed [15:0] dout")
lines.append(");")
lines.append("    reg signed [15:0] rom [0:255];")
lines.append("    integer i;")
lines.append("    initial begin")
lines.append("        for (i = 0; i < 256; i = i + 1) rom[i] = 16'sd0;")
for idx, c in enumerate(rows):
    for k in range(5):
        v = c[k]
        txt = ("-16'sd%d" % -v) if v < 0 else ("16'sd%d" % v)
        lines.append("        rom[%d] = %s;" % (idx * 5 + k, txt))
lines.append("    end")
lines.append("    always @(posedge clk) dout <= rom[addr];")
lines.append("endmodule")

out = "user_source/hdl_source/audio/audio_eq_coeff_rom.v"
with open(out, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", out, "rows", len(rows))

# Analytic response table (dB) for the testbench: band preset curves.
PRESETS = {
    1: [6, 3, 0, 0, -3],
    2: [-3, 0, 0, 3, 6],
    3: [6, 3, 0, 3, 6],
}
for eff, gains in PRESETS.items():
    print("effect", eff, gains)

TEST_FREQS = [50, 100, 300, 1000, 3000, 8000, 12000]
print("response table (dB, quantized coefficients, cascade of 5 bands):")
for eff, gains in PRESETS.items():
    vals = []
    for f in TEST_FREQS:
        z = complex(math.cos(2 * math.pi * f / FS), -math.sin(2 * math.pi * f / FS))
        h = 1.0 + 0j
        for b, gdb in enumerate(gains):
            c = coeffs(b, gdb)
            c = [x / 8192.0 for x in c]
            num = c[0] + c[1] / z + c[2] / (z * z)
            den = 1.0 + c[3] / z + c[4] / (z * z)
            h *= num / den
        vals.append(20 * math.log10(abs(h)))
    print("effect", eff, " ".join("%.2f" % v for v in vals))
