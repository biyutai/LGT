"""Check that every visible character of a playlist has a 16x16 glyph.

The 16x16 OSD font is a fixed ROM generated by scripts/gen_osd_chinese_font.py.
Playlist subtitles are written by hand, so a character that is not in the ROM
silently renders as a blank box. The '|' bilingual separator is not rendered.
Run this before shipping a new PLAYLIST.TXT; --text checks a legacy TEXT.TXT.

用法：python scripts/check_playlist_font.py [--playlist P] [--text T]
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def font_chars(generator: Path) -> set[str]:
    source = generator.read_text(encoding="utf-8")
    chars = "".join(m.group(1) for m in re.finditer(r'CHARS \+= "([^"]*)"', source))
    first = re.search(r'CHARS = "([^"]*)"', source)
    if first:
        chars = first.group(1) + chars
    return set(chars)


def subtitle_text(path: Path) -> str:
    text = ""
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        fields = line.split(",", 3)
        text += (fields[3] if len(fields) >= 4 else line).replace("|", "")
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--playlist", type=Path,
                        default=ROOT / "assets/scale_demo/PLAYLIST.TXT")
    parser.add_argument("--text", type=Path)
    parser.add_argument("--generator", type=Path,
                        default=ROOT / "scripts/gen_osd_chinese_font.py")
    args = parser.parse_args()

    have = font_chars(args.generator)
    missing: dict[str, str] = {}
    for path in (args.playlist, args.text):
        if path is None:
            continue
        if not path.exists():
            print("skip  %s (not found)" % path.name)
            continue
        for char in subtitle_text(path):
            if char in " \t" or char in have:
                continue
            missing.setdefault(char, path.name)

    print("font glyphs: %d / 255 used" % len(have))
    if not missing:
        print("OK: every visible subtitle character has a glyph")
        return 0
    for char, name in missing.items():
        print("MISSING U+%04X %r  (used by %s)" % (ord(char), char, name))
    print("%d character(s) missing; add them to CHARS in %s and re-run it"
          % (len(missing), args.generator.name))
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
